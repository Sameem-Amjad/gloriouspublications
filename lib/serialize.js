/** Mongoose documents to plain JSON for client components. */
export const plain = (doc) => JSON.parse(JSON.stringify(doc));

export const slugify = (s) =>
  String(s)
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
